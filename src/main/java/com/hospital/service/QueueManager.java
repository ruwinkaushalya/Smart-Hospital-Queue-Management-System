    // ==================== CW SCOPE: UNDO STACK FEATURES ====================
    public String undoLastAction() {
        String action = undoStack.pop();
        if (action == null) return null;
        String[] parts = action.split(":");
        if (parts.length < 2) return action;
        if ("REGISTER_PATIENT".equals(parts[0]) && parts.length >= 2) {
            removePatient(parts[1]);
        } else if ("ALLOCATE_BED".equals(parts[0]) && parts.length >= 3) {
            // Reverse bed allocation by discharging
            dischargeBed(parts[1], parts[2]);
        }
        return action;
    }

