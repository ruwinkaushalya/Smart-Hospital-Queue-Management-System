    private Doctor findBestDoctor(Hospital hospital, Patient patient) {
        Doctor best = null;
        double bestScore = -1;
        for (Doctor d : doctors) {
            if (!d.getHospitalId().equals(hospital.getId())) continue;
            if (!d.isAvailable()) continue;

            double score = 0.0;
            // Specialty matching bonus
            if (patient.getSymptoms().toLowerCase().contains("chest") && d.getSpecialty().equalsIgnoreCase("Cardiology")) {
                score += 2.0;
            } else if (patient.getSymptoms().toLowerCase().contains("broken") && d.getSpecialty().equalsIgnoreCase("Orthopedics")) {
                score += 2.0;
            } else if (patient.getSymptoms().toLowerCase().contains("child") && d.getSpecialty().equalsIgnoreCase("Pediatrics")) {
                score += 2.0;
            } else if (d.getSpecialty().equalsIgnoreCase("Emergency Medicine")) {
                score += 1.0;
            } else {
                score += 0.5;
            }
            // Prefer doctors with fewer patients today
            score += (1.0 - (double) d.getPatientsToday() / Math.max(d.getMaxPatientsPerDay(), 1));

            if (score > bestScore) {
                bestScore = score;
                best = d;
            }
        }
        return best;
    }

