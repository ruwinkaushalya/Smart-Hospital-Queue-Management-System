    public Invoice generateInvoiceFromVisit(String visitId) {
        if (autoGeneratedVisitIds.contains(visitId)) {
            throw new IllegalStateException("Invoice already generated for this visit");
        }
        com.hospital.model.VisitRecord visit = patientHistory.findVisit(visitId);
        if (visit == null) return null;
        Invoice.InvoiceType invoiceType = mapVisitTypeToInvoiceType(visit.getType());
        double baseAmount = visit.getTotalCost() > 0 ? visit.getTotalCost() : 100.0;
        String description = String.format("Auto-generated from visit %s: %s - %s",
                visit.getId(), visit.getDiagnosis(), visit.getTreatment());
        Invoice invoice = new Invoice(visit.getPatientId(), visit.getPatientName(), invoiceType,
                baseAmount, description, visit.getHospitalName(), visit.getDoctorName());
        invoices.add(invoice);
        autoGeneratedVisitIds.add(visitId);
        try {
            invoiceRepo.save(invoice);
        } catch (Exception e) {
            System.err.println("Failed to save invoice to database: " + e.getMessage());
            invoices.remove(invoice);
            autoGeneratedVisitIds.remove(visitId);
            return null;
        }
        notifyListeners();
        return invoice;
    }

    private static Invoice.InvoiceType mapVisitTypeToInvoiceType(com.hospital.model.VisitRecord.VisitType type) {
        switch (type) {
            case EMERGENCY: return Invoice.InvoiceType.EMERGENCY;
            case SURGERY: return Invoice.InvoiceType.SURGERY;
            case INPATIENT: return Invoice.InvoiceType.BED_CHARGE;
            case OUTPATIENT: return Invoice.InvoiceType.CONSULTATION;
            case CONSULTATION: return Invoice.InvoiceType.CONSULTATION;
            case FOLLOW_UP: return Invoice.InvoiceType.CONSULTATION;
            case CHECKUP: return Invoice.InvoiceType.LAB_TEST;
            default: return Invoice.InvoiceType.CONSULTATION;
        }
    }

