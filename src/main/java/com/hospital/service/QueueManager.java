    public boolean registerPatient(Patient patient, boolean sendNotifications) {
        try {
            patientRepo.save(patient);
        } catch (Exception e) {
            System.err.println("Failed to save patient to database: " + e.getMessage());
            return false;
        }
        boolean added = patientQueue.addPatient(patient);
        if (added) {
            undoStack.push("REGISTER_PATIENT:" + patient.getId());
            // Notify if critical patient
            if (sendNotifications && patient.getSeverity() == Patient.Severity.CRITICAL) {
                notificationService.notifyCriticalPatientQueued(patient);
            }
            recalculateWaitTimes();
            notifyListeners();
        }
        return added;
    }

    public Patient processNextPatient() {
        Patient patient = patientQueue.processNextPatient();
        if (patient != null) {
            Hospital assigned = findBestHospital(patient);
            if (assigned != null) {
                String oldAssignedHospital = patient.getAssignedHospital();
                int oldBeds = assigned.getAvailableBeds();
                int oldICU = assigned.getAvailableICU();
                int oldDoctors = assigned.getAvailableDoctors();
                patient.setAssignedHospital(assigned.getName());
                assigned.allocateResources(patient);

                // Assign doctor
                Doctor doctor = findBestDoctor(assigned, patient);
                String oldDoctorId = patient.getAssignedDoctorId();
                String oldDoctorName = patient.getAssignedDoctorName();
                if (doctor != null) {
                    doctor.assignPatient(patient.getId());
                    patient.setAssignedDoctorId(doctor.getId());
                    patient.setAssignedDoctorName(doctor.getName());
                }

                patient.setTreatmentStartTime(java.time.LocalDateTime.now());
                patient.setStatus(Patient.PatientStatus.IN_TREATMENT);
                patient.setTreated(true);

                try {
                    hospitalRepo.updateResources(assigned);
                    if (doctor != null) {
                        doctorRepo.update(doctor);
                    }
                    patientRepo.update(patient);
                    if (doctor != null) {
                        notificationService.notifyDoctorAssigned(patient, doctor.getName(), doctor.getSpecialty());
                    }
                } catch (Exception e) {
                    // Rollback in-memory state on DB failure
                    patient.setAssignedHospital(oldAssignedHospital);
                    patient.setAssignedDoctorId(oldDoctorId);
                    patient.setAssignedDoctorName(oldDoctorName);
                    patient.setStatus(Patient.PatientStatus.WAITING);
                    patient.setTreated(false);
                    patient.setTreatmentStartTime(null);
                    assigned.setAvailableBeds(oldBeds);
                    assigned.setAvailableICU(oldICU);
                    assigned.setAvailableDoctors(oldDoctors);
                    if (doctor != null) {
                        doctor.releasePatient();
                        doctor.setPatientsToday(doctor.getPatientsToday() - 1);
                    }
                    throw new RuntimeException("Failed to persist patient processing", e);
                }
            } else {
                // No bed available — add to pending bed list
                patient.setStatus(Patient.PatientStatus.PENDING_BED);
                pendingBedPatients.add(patient);
                try {
                    patientRepo.update(patient);
                } catch (Exception e) {
                    pendingBedPatients.remove(patient);
                    patient.setStatus(Patient.PatientStatus.WAITING);
                    throw new RuntimeException("Failed to persist pending bed status", e);
                }
                notificationService.notifyBedPending(patient);
            }
            recalculateWaitTimes();
            notifyListeners();
        }
        return patient;
    }

    public boolean removePatient(String patientId) {
        boolean removed = patientQueue.removePatient(patientId);
        if (removed) {
            recalculateWaitTimes();
            notifyListeners();
        }
        return removed;
    }

    private void recalculateWaitTimes() {
        List<Patient> emergency = patientQueue.getEmergencyQueue();
        List<Patient> normal = patientQueue.getNormalQueue();
        Hospital defaultHospital = hospitals.isEmpty() ? null : hospitals.get(0);

        int emergencyAhead = 0;
        for (Patient p : emergency) {
            int waitTime = aiSupport.predictWaitTimeMinutes(p, emergencyAhead, defaultHospital);
            p.setEstimatedWaitTimeMinutes(waitTime);
            double score = aiSupport.calculatePriorityScore(p, emergencyAhead, emergency.size() + normal.size());
            p.setAiPriorityScore(score);
            emergencyAhead++;
        }

        int normalAhead = 0;
        for (Patient p : normal) {
            int waitTime = aiSupport.predictWaitTimeMinutes(p, emergencyAhead + normalAhead, defaultHospital);
            p.setEstimatedWaitTimeMinutes(waitTime);
            double score = aiSupport.calculatePriorityScore(p, emergencyAhead + normalAhead, emergency.size() + normal.size());
            p.setAiPriorityScore(score);
            normalAhead++;
        }
    }

    private Hospital findBestHospital(Patient patient) {
        Hospital best = null;
        double bestScore = -1;

        for (Hospital h : hospitals) {
            boolean canAccept = patient.getSeverity().getPriorityValue() >= 4
                    ? h.canAcceptEmergency()
                    : h.canAcceptNormal();
            if (!canAccept) continue;

            double score = (1.0 - h.getLoadFactor()) * 0.5
                        + (h.getAvailableDoctors() / Math.max(h.getEmergencyDoctors(), 1.0)) * 0.3
                        + (h.isHasEmergencyUnit() ? 0.2 : 0.0);

            if (score > bestScore) {
                bestScore = score;
                best = h;
            }
        }
        return best;
    }

