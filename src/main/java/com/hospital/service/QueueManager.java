    public Report getReport(String id) {
        // Load from DB to get full base64 content (in-memory copies are stripped)
        try {
            Report full = reportRepo.findById(id);
            if (full != null) return full;
        } catch (Exception e) {
            System.err.println("DB lookup failed for report " + id + ", falling back to memory: " + e.getMessage());
        }
        // Fallback to in-memory list if DB not available
        for (Report r : reports) {
            if (r.getId().equals(id)) return r;
        }
        return null;
    }

    public boolean updateReportStatus(String reportId, String status, String doctorName) {
        for (Report r : reports) {
            if (r.getId().equals(reportId)) {
                r.setStatus(status);
                if (doctorName != null) r.setDoctorName(doctorName);
                try {
                    reportRepo.updateStatus(reportId, status, doctorName);
                } catch (Exception e) {
                    System.err.println("Failed to update report status: " + e.getMessage());
                    return false;
                }
                notifyListeners();
                return true;
            }
        }
        return false;
    }

    public boolean deleteReport(String reportId) {
        Report toRemove = null;
        for (Report r : reports) {
            if (r.getId().equals(reportId)) {
                toRemove = r;
                break;
            }
        }
        if (toRemove != null) {
            reports.remove(toRemove);
            try {
                reportRepo.delete(reportId);
            } catch (Exception e) {
                System.err.println("Failed to delete report: " + e.getMessage());
                reports.add(toRemove);
                return false;
            }
            notifyListeners();
            return true;
        }
        return false;
    }

    public int getReportCount() {
        return reports.size();
    }

