    public boolean allocateBed(String hospitalId, String bedType) {
        for (Hospital h : hospitals) {
            if (h.getId().equals(hospitalId)) {
                int oldBeds = h.getAvailableBeds();
                int oldICU = h.getAvailableICU();
                boolean changed = false;
                if ("ICU".equalsIgnoreCase(bedType) && h.getAvailableICU() > 0) {
                    h.setAvailableICU(h.getAvailableICU() - 1);
                    changed = true;
                } else if (h.getAvailableBeds() > 0) {
                    h.setAvailableBeds(h.getAvailableBeds() - 1);
                    changed = true;
                }
                if (changed) {
                    try {
                        hospitalRepo.updateResources(h);
                        undoStack.push("ALLOCATE_BED:" + hospitalId + ":" + bedType);
                        notifyListeners();
                        return true;
                    } catch (Exception e) {
                        h.setAvailableBeds(oldBeds);
                        h.setAvailableICU(oldICU);
                        return false;
                    }
                }
                return false;
            }
        }
        return false;
    }

    public boolean dischargeBed(String hospitalId, String bedType) {
        for (Hospital h : hospitals) {
            if (h.getId().equals(hospitalId)) {
                int oldBeds = h.getAvailableBeds();
                int oldICU = h.getAvailableICU();
                boolean changed = false;
                if ("ICU".equalsIgnoreCase(bedType) && h.getAvailableICU() < h.getTotalICU()) {
                    h.setAvailableICU(h.getAvailableICU() + 1);
                    changed = true;
                } else if (h.getAvailableBeds() < h.getTotalBeds()) {
                    h.setAvailableBeds(h.getAvailableBeds() + 1);
                    changed = true;
                }
                if (changed) {
                    try {
                        hospitalRepo.updateResources(h);
                        // Check pending bed patients and assign if possible
                        assignPendingBedPatients(h);
                        notifyListeners();
                        return true;
                    } catch (Exception e) {
                        h.setAvailableBeds(oldBeds);
                        h.setAvailableICU(oldICU);
                        return false;
                    }
                }
                return false;
            }
        }
        return false;
    }

    private void assignPendingBedPatients(Hospital hospital) {
        Iterator<Patient> it = pendingBedPatients.iterator();
        while (it.hasNext()) {
            Patient p = it.next();
            boolean canAccept = p.getSeverity().getPriorityValue() >= 4
                    ? hospital.canAcceptEmergency()
                    : hospital.canAcceptNormal();
            if (canAccept) {
                String oldHospital = p.getAssignedHospital();
                int oldBeds = hospital.getAvailableBeds();
                int oldICU = hospital.getAvailableICU();
                int oldDoctors = hospital.getAvailableDoctors();
                p.setAssignedHospital(hospital.getName());
                hospital.allocateResources(p);
                p.setStatus(Patient.PatientStatus.IN_TREATMENT);
                p.setTreated(true);
                p.setTreatmentStartTime(java.time.LocalDateTime.now());

                Doctor doctor = findBestDoctor(hospital, p);
                if (doctor != null) {
                    doctor.assignPatient(p.getId());
                    p.setAssignedDoctorId(doctor.getId());
                    p.setAssignedDoctorName(doctor.getName());
                }

                try {
                    hospitalRepo.updateResources(hospital);
                    if (doctor != null) doctorRepo.update(doctor);
                    patientRepo.update(p);
                    notificationService.notifyBedAvailable(p, hospital.getName());
                    it.remove();
                } catch (Exception e) {
                    p.setAssignedHospital(oldHospital);
                    p.setStatus(Patient.PatientStatus.PENDING_BED);
                    p.setTreated(false);
                    p.setTreatmentStartTime(null);
                    hospital.setAvailableBeds(oldBeds);
                    hospital.setAvailableICU(oldICU);
                    hospital.setAvailableDoctors(oldDoctors);
                    if (doctor != null) {
                        doctor.releasePatient();
                        doctor.setPatientsToday(doctor.getPatientsToday() - 1);
                    }
                    break;
                }
            }
        }
    }

